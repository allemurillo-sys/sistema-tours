const idiomaValido = (x) => (x && Object.prototype.hasOwnProperty.call(IDIOMAS, x) ? x : null);

// Idioma elegido a propósito: en el enlace (?lang=en) o guardado en este navegador
function idiomaExplicito() {
  const enlace = idiomaValido(new URLSearchParams(location.search).get("lang"));
  if (enlace) return enlace;
  try { return idiomaValido(localStorage.getItem(CLAVE_IDIOMA)); } catch { return null; }
}

// Idioma del navegador del cliente, si es uno de los cinco
function idiomaNavegador() {
  const lista = navigator.languages?.length ? navigator.languages : [navigator.language || ""];
  for (const l of lista) {
    const codigo = idiomaValido(String(l).slice(0, 2).toLowerCase());
    if (codigo) return codigo;
  }
  return "es";
}

let idioma = idiomaExplicito() || idiomaNavegador();

function t(clave, vars = {}) {
  const texto = TEXTOS[idioma]?.[clave] ?? TEXTOS.es[clave] ?? clave;
  return texto.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}
const tp = (base, n, vars = {}) => t(`${base}_${n === 1 ? "1" : "n"}`, { n, ...vars });
const locale = () => LOCALES[idioma];

// Traduce el nombre de un tipo de cliente del catálogo, si se conoce
function tCategoria(nombre) {
  const clave = `cat_${nombre}`;
  return TEXTOS[idioma]?.[clave] ?? nombre;
}

// Nombre de una actividad o de un tipo en el idioma actual (si no hay traducción, en español)
function tServicio(s) {
  return (idioma !== "es" && s?.traducciones?.[idioma]?.nombre) || s?.nombre || "";
}
function tDescripcion(s) {
  if (idioma === "es") return s?.descripcion || "";
  return s?.traducciones?.[idioma]?.descripcion || "";
}
function tTipo(tipo) {
  return (idioma !== "es" && tipo?.traducciones?.[idioma]) || tipo?.nombre || "";
}

function aplicarTextos() {
  document.documentElement.lang = idioma;
  if (document.body.dataset.titulo) document.title = t(document.body.dataset.titulo);
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  const selector = document.getElementById("selectorIdioma");
  if (selector) {
    selector.value = idioma;
    selector.setAttribute("aria-label", t("idioma"));
  }
}

function cambiarIdioma(nuevo, guardar = true) {
  nuevo = idiomaValido(nuevo);
  if (!nuevo) return;
  idioma = nuevo;
  if (guardar) {
    try { localStorage.setItem(CLAVE_IDIOMA, nuevo); } catch { /* navegador sin almacenamiento */ }
  }
  aplicarTextos();
  document.dispatchEvent(new Event("idioma-cambiado"));
}

(function iniciarSelectorIdioma() {
  const selector = document.getElementById("selectorIdioma");
  if (selector) {
    selector.innerHTML = Object.entries(IDIOMAS)
      .map(([codigo, nombre]) => `<option value="${codigo}" lang="${codigo}">${nombre}</option>`).join("");
    selector.addEventListener("change", () => cambiarIdioma(selector.value));
  }
  aplicarTextos();
})();
